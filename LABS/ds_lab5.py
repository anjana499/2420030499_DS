import pandas as pd
import seaborn as sns
from sklearn.preprocessing import StandardScaler
from sklearn.decomposition import PCA

# Load dataset
tips = sns.load_dataset("tips")

numeric_cols = tips.select_dtypes(include=['float64', 'int64']).columns

# Standardize the data
scaler = StandardScaler()
scaled_data = scaler.fit_transform(tips[numeric_cols])

# Perform PCA
pca = PCA(n_components=2)
pca_result = pca.fit_transform(scaled_data)

# Create a new DataFrame with principal components
principal_df = pd.DataFrame(data=pca_result, columns=['PC1', 'PC2'])

print("Explained variance ratio:")
print(pca.explained_variance_ratio_)

print("\nPrincipal components:")
print(principal_df.head())

import matplotlib.pyplot as plt

plt.scatter(principal_df['PC1'], principal_df['PC2'])

plt.xlabel('Principal Component 1')
plt.ylabel('Principal Component 2')

plt.title('PCA Projection of Tips Dataset')

plt.show()