import pandas as pd

import seaborn as sns

import matplotlib.pyplot as plt

df = sns.load_dataset('tips')

# Histogram

plt.figure(figsize=(6,4))

sns.histplot(df['total_bill'], bins=20, kde=True)

plt.title('Histogram of Total Bill')

plt.show()


# Box Plot

plt.figure(figsize=(6,4))

sns.boxplot(df['total_bill'])

plt.title('Box Plot of Total Bill')

plt.show()


# Pie Chart

day_count = df['day'].value_counts()

plt.figure(figsize=(6,4))

plt.pie(day_count, labels=day_count.index, autopct='%1.1f%%')

plt.title('Day Distribution (Pie Chart)')

plt.show()


# Scatter Plot

plt.figure(figsize=(6,4))

sns.scatterplot(x=df['total_bill'], y=df['tip'], hue=df['day'])

plt.title('Scatter Plot of Total Bill vs Tip')

plt.show()


# Line Plot

plt.figure(figsize=(6,4))

plt.plot(df['total_bill'])

plt.title('Line Plot of Total Bill')

plt.xlabel("Sample Index")

plt.ylabel("Total Bill")

plt.show()


# Bar Chart

plt.figure(figsize=(6,4))

sns.barplot(x=df['day'], y=df['total_bill'])

plt.title('Bar Chart: Mean Total Bill by Day')

plt.show()


# Heatmap

plt.figure(figsize=(8,6))

sns.heatmap(df[['total_bill','tip','size']].corr(), annot=True, cmap="coolwarm")

plt.title("Heatmap of Feature Correlation")

plt.show()


# Bubble Chart

plt.figure(figsize=(6,4))

sns.scatterplot(x=df['total_bill'], y=df['tip'],

                s=df['size'] * 20, alpha=0.5, hue=df['day'])

plt.title('Bubble Chart: Total Bill vs Tip')

plt.xlabel("Total Bill")

plt.ylabel("Tip")

plt.show()


# Violin Plot

plt.figure(figsize=(6,4))

sns.violinplot(x=df['day'], y=df['total_bill'])

plt.title('Violin Plot of Total Bill by Day')

plt.xlabel("Day")

plt.ylabel("Total Bill")

plt.show()